// Урок 3, задание: «ровно две из четырёх».
// LED0 горит, когда нажаты (включены) ровно два входа из четырёх.
// Таблица истинности на 4 входа = одна LUT4.
module top (
    input  wire btn_s1,   // кнопка S1, вывод 88, нажата = 1
    input  wire btn_s2,   // кнопка S2, вывод 87, нажата = 1
    input  wire in3,      // провод на выводе 73 (левая гребёнка, контакт 1)
    input  wire in4,      // провод на выводе 74 (левая гребёнка, контакт 2)
    output wire led0      // LED0, вывод 15, горит при 0
);
    wire a, b, c, d, two;
    assign a = btn_s1;
    assign b = btn_s2;
    assign c = in3;
    assign d = in4;

    // Шесть способов выбрать пару из четырёх; остальные два входа должны быть 0.
    assign two = (a & b & ~c & ~d) | (a & ~b & c & ~d) | (a & ~b & ~c & d)
               | (~a & b & c & ~d) | (~a & b & ~c & d) | (~a & ~b & c & d);

    assign led0 = ~two;   // светодиод горит по нулю
endmodule
