// Урок 10, практика 1: один цвет константой на светодиоде WS2812 платы.
// Передатчик ws2812_tx (файл ws2812_tx.v) шлёт цвет снова и снова:
// кадр 24 бита (≈ 31 мкс) + пауза 300 мкс, около 3000 раз в секунду.
module top #(
    parameter integer CLK_HZ = 27_000_000   // частота clk
) (
    input  wire clk,            // 27 МГц, вывод 4
    output wire ws2812          // линия данных WS2812, вывод 79
);
    // Цвет: оранжевый, не на полную яркость (255 может слепить — ⚠️ проверить).
    localparam [7:0] RED   = 8'h40;
    localparam [7:0] GREEN = 8'h10;
    localparam [7:0] BLUE  = 8'h00;

    ws2812_tx #(.CLK_HZ(CLK_HZ)) led0 (
        .clk   (clk),
        .start (1'b1),          // всегда «отправь»: новый кадр сразу после паузы
        .r     (RED),
        .g     (GREEN),
        .b     (BLUE),
        .dout  (ws2812),
        .busy  ()               // не нужен: start и так всегда 1
    );
endmodule
