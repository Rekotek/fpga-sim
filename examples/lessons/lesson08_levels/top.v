// Урок 8, практика 1: шесть светодиодов с разной постоянной яркостью.
// ШИМ = свободно бегущий счётчик + сравнение: pwm = (cnt < duty).
// Каждый следующий светодиод получает вдвое меньшую долю «горит».
module top (
    input  wire       clk,      // 27 МГц, вывод 4
    output wire [5:0] led       // LED0..LED5, выводы 15..20, горят при 0
);
    // Счётчик ШИМ: 8 бит, считает 0, 1, …, 255, 0, 1, … без остановки.
    // Период ШИМ = 256 тактов: 27 000 000 / 256 ≈ 105 кГц.
    reg [7:0] cnt = 8'd0;

    always @(posedge clk)
        cnt <= cnt + 1'b1;          // после 255 сам переходит в 0

    // Коэффициент заполнения каждого светодиода: сколько тактов из 256 он горит.
    localparam [7:0] D0 = 8'd255,   // 255/256 ≈ 100 %
                     D1 = 8'd128,   // 50 %
                     D2 = 8'd64,    // 25 %
                     D3 = 8'd32,    // 12,5 %
                     D4 = 8'd16,    // 6,25 %
                     D5 = 8'd8;     // 3,125 %

    // Компараторы: 1 («горит»), пока счётчик меньше порога.
    wire [5:0] pwm = { cnt < D5, cnt < D4, cnt < D3,
                       cnt < D2, cnt < D1, cnt < D0 };

    assign led = ~pwm;              // светодиоды горят по нулю
endmodule
