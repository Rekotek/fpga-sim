// Урок 5: бегущий огонь на шести светодиодах.
// Сдвиговый регистр из 6 триггеров, замкнутый в кольцо: одна «1» бежит по кругу.
// Шаг — 8 раз в секунду: делитель даёт тик, регистр сдвигается только по тику.
module top #(
    parameter integer CLK_HZ = 27_000_000   // частота clk; тестбенч ставит меньше
) (
    input  wire       clk,   // 27 МГц, вывод 4
    output wire [5:0] led    // LED0..LED5, выводы 15..20, горят при 0
);
    // Делитель: тик раз в 1/8 с. Считаем 0..LAST, это CLK_HZ / 8 тактов.
    localparam integer LAST = CLK_HZ / 8 - 1;   // 3 374 999 при 27 МГц
                                                // 3 374 999 < 2^22 = 4 194 304 → 22 бита
    reg  [21:0] div = 22'd0;
    wire        tick = (div == LAST);           // 1 ровно на один такт из 3 375 000

    always @(posedge clk) begin
        if (tick) div <= 22'd0;
        else      div <= div + 1'b1;
    end

    // Регистр из 6 триггеров. Старт: горит только LED0.
    reg [5:0] sr = 6'b000001;

    always @(posedge clk) begin
        if (tick)
            sr <= {sr[4:0], sr[5]};   // все биты на одну позицию влево, sr[5] — в sr[0]
    end

    assign led = ~sr;   // светодиоды горят по нулю
endmodule
