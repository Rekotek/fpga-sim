// Пример для платы Tang Nano 9K.
// Ожидаемое поведение: счётчик прибавляет 1 каждые 0,25 с и идёт на шесть светодиодов:
// led[0] переключается 4 раза в секунду, led[5] — раз в 8 с.
// Проверочное число: S1 нажата с 1,1 до 1,6 с, S2 — с 2,1 до 2,2 с; за 2,6 с вывод 10
// переключается 7 раз, вывод 11 — 4 раза, вывод 13 — 2 раза.
// Пока нажата кнопка S1, счёт стоит. Нажатие S2 обнуляет счётчик. Светодиоды горят при нуле.
// Кнопки платы замыкают вывод на землю: нажата = 0. На плате у кнопок есть резисторы подтяжки
// к 1,8 В, поэтому PULL_MODE=UP в top.cst необязательна.
// Кнопки и светодиоды 9K стоят в банке 1,8 В, поэтому в top.cst у них IO_TYPE=LVCMOS18.
module top (
    input  wire       clk,      // 27 МГц, вывод 52
    input  wire       btn_s1,   // кнопка S1, вывод 3
    input  wire       btn_s2,   // кнопка S2, вывод 4
    output wire [5:0] led       // светодиоды, выводы 10, 11, 13, 14, 15, 16
);
    localparam integer CLK_HZ = 27_000_000;
    localparam integer TICK   = CLK_HZ / 4;      // период счёта: 0,25 с

    reg [22:0] div = 0;
    reg [5:0]  cnt = 0;
    reg [1:0]  s1  = 2'b11, s2 = 2'b11;          // синхронизаторы кнопок

    always @(posedge clk) begin
        s1 <= {s1[0], btn_s1};
        s2 <= {s2[0], btn_s2};
        if (!s2[1]) begin
            div <= 0;
            cnt <= 0;
        end else if (s1[1]) begin
            if (div == TICK - 1) begin
                div <= 0;
                cnt <= cnt + 1'b1;
            end else begin
                div <= div + 1'b1;
            end
        end
    end

    assign led = ~cnt;
endmodule
