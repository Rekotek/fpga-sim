// Ожидаемое поведение: led[0] плавно разгорается и плавно гаснет, полный круг — 2,476 с.
// led[1] горит постоянно на 1/8 яркости, led[2..5] погашены. Светодиоды горят при нуле.
//
// Яркость задаёт ШИМ: счётчик pwm считает от 0 до 255 (период 256 тактов, 105 469 Гц),
// светодиод включён, пока pwm меньше уровня level. Уровень меняется на единицу раз
// в 131 072 такта: от 0 до 255 и обратно до 0, всего 510 ступеней на круг.
//
// Проверочные числа. После n тактов уровень равен tri(floor(n / 131072) mod 510),
// где tri(m) = m при m <= 255 и 510 - m иначе; яркость led[0] равна level / 256:
//   такт  4 259 840 (ступень  32,5): яркость  32/256 = 0,125
//   такт 16 842 752 (ступень 128,5): яркость 128/256 = 0,500
//   такт 29 425 664 (ступень 224,5): яркость 224/256 = 0,875
//   такт 50 135 040 (ступень 382,5): яркость 128/256 = 0,500 (уровень уже убывает)
// За 2,5 с времени симуляции вывод 16 (led[1]) переключается 527 343 раза и проводит
// в единице 7/8 времени; вывод 15 (led[0]) проводит в единице около половины времени.
module top (
    input  wire       clk,
    output wire [5:0] led
);
    reg [7:0]  pwm   = 0;
    reg [16:0] div   = 0;
    reg [7:0]  level = 0;
    reg        up    = 1'b1;

    always @(posedge clk) begin
        pwm <= pwm + 1'b1;
        div <= div + 1'b1;
        if (div == 17'h1FFFF) begin
            if (up) begin
                if (level == 8'd254) up <= 1'b0;
                level <= level + 1'b1;
            end else begin
                if (level == 8'd1) up <= 1'b1;
                level <= level - 1'b1;
            end
        end
    end

    wire fade = pwm < level;
    wire dim  = pwm < 8'd32;

    assign led = {4'b1111, ~dim, ~fade};
endmodule
